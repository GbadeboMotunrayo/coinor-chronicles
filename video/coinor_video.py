def env_value(name):
    try:
        for line in open(CFG["env_file"], encoding="utf-8").read().splitlines():
            if line.startswith(name + "="):
                return line.split("=", 1)[1].strip().strip("\"'")
    except OSError:
        pass
    return ""


def upload_youtube(mp4, meta, urlopen=urllib.request.urlopen):
    cid, sec, rt = env_value("YT_CLIENT_ID"), env_value("YT_CLIENT_SECRET"), env_value("YT_REFRESH_TOKEN")
    if not (cid and sec and rt):
        return {"uploaded": False, "why": "no YouTube keys yet"}
    tok = json.loads(urlopen(urllib.request.Request("https://oauth2.googleapis.com/token", urllib.parse.urlencode(
        {"client_id": cid, "client_secret": sec, "refresh_token": rt, "grant_type": "refresh_token"}).encode()), timeout=30).read())["access_token"]
    body = json.dumps({"snippet": {"title": meta["title"], "description": meta["description"], "tags": meta["tags"], "categoryId": meta["category"]},
                       "status": {"privacyStatus": CFG["yt_privacy"], "selfDeclaredMadeForKids": False, "containsSyntheticMedia": meta["synthetic"]}}).encode()
    init = urllib.request.Request("https://www.googleapis.com/upload/youtube/v3/videos?uploadType=resumable&part=snippet,status", body,
                                  {"Authorization": "Bearer " + tok, "Content-Type": "application/json; charset=UTF-8",
                                   "X-Upload-Content-Type": "video/mp4", "X-Upload-Content-Length": str(os.path.getsize(mp4))})
    loc = urlopen(init, timeout=60).headers["Location"]
    put = urllib.request.Request(loc, open(mp4, "rb").read(), {"Content-Type": "video/mp4"}, method="PUT")
    res = json.loads(urlopen(put, timeout=900).read())
    return {"uploaded": True, "id": res.get("id"), "url": f"https://youtu.be/{res.get('id')}", "privacy": CFG["yt_privacy"]}


def notify(msg):
    cmd = ["hermes", "send", "--to", CFG["chairman"]]
    if os.geteuid() == 0:
        cmd = ["sudo", "-u", "hermes"] + cmd
    try:
        subprocess.run(cmd, input=msg, text=True, capture_output=True, timeout=30)
    except Exception:
        pass


# ----------------------------------------------------------------------------- the daily job
def make(date=None, number=None, force=False, upload=True, dry=False, now=None):
    now = now or dt.datetime.now(dt.timezone.utc)
    date = date or (now + dt.timedelta(hours=CFG["tz_hours"])).date().isoformat()
    feed = read_json(CFG["feed"], {"episodes": []})
    ep = pick_episode(feed, date, number)
    if not ep:
        log("no_chapter_today", date=date)
        return {"outcome": "no_chapter", "date": date}
    st = read_json(CFG["state"], {"made": {}})
    key = f"ep{ep['number']}"
    if key in st["made"] and not force and not dry:
        return {"outcome": "already_made", "episode": ep["number"]}
    if dry:
        sents = narration(ep["body"], CFG["max_words"]) + [OUTRO]
        return {"outcome": "dry_run", "episode": ep["number"], "words": sum(len(s.split()) for s in sents), "scenes": [image_prompt(s)[:90] for s in scenes(ep)]}
    os.makedirs(CFG["out_dir"], exist_ok=True)
    name = f"coinor-{date}-ep{ep['number']}.mp4"; out = os.path.join(CFG["out_dir"], name)
    work = tempfile.mkdtemp(prefix="coinor-video-")
    try:
        info = build(ep, work, out)
    except Exception as e:
        log("video_failed", episode=ep["number"], why=str(e)[:300])
        notify(f"CoinorChronicles video for Episode {ep['number']} failed: {str(e)[:160]}")
        return {"outcome": "failed", "episode": ep["number"], "why": str(e)[:300]}
    finally:
        shutil.rmtree(work, ignore_errors=True)
    meta = metadata(ep); json.dump(meta, open(out[:-4] + ".json", "w"), indent=2, ensure_ascii=False)
    up = {"uploaded": False, "why": "skipped"}
    if upload:
        try:
            up = upload_youtube(out, meta)
        except Exception as e:
            up = {"uploaded": False, "why": f"upload error: {type(e).__name__}"}
    st["made"][key] = {"file": name, "at": now.isoformat(timespec="seconds"), "seconds": info["seconds"], "uploaded": up.get("uploaded", False)}
    os.makedirs(os.path.dirname(CFG["state"]), exist_ok=True); json.dump(st, open(CFG["state"], "w"), indent=2)
    cutoff = time.time() - CFG["keep_days"] * 86400
    for f in glob.glob(os.path.join(CFG["out_dir"], "coinor-*")):
        if os.path.getmtime(f) < cutoff:
            os.remove(f)
    url = f"{CFG['public_base']}/{name}"
    log("video_made", episode=ep["number"], seconds=info["seconds"], url=url, upload=up)
    notify(f"Daily video ready: Episode {ep['number']}, {info['seconds']}s.\nDownload: {url}\n" +
           (f"YouTube ({up['privacy']}): {up['url']}" if up.get("uploaded") else f"Not on YouTube yet ({up.get('why')}). Upload it by hand or finish the YouTube setup."))
    return {"outcome": "made", "episode": ep["number"], "file": name, "url": url, "upload": up, **{k: info[k] for k in ("seconds", "words")}}


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    m = sub.add_parser("make"); m.add_argument("--episode", type=int); m.add_argument("--date"); m.add_argument("--force", action="store_true")
    m.add_argument("--no-upload", action="store_true"); m.add_argument("--dry-run", action="store_true")
    sub.add_parser("status")
    a = ap.parse_args(argv)
    if a.cmd == "status":
        print(json.dumps(read_json(CFG["state"], {"made": {}}), indent=2)); return
    print(json.dumps(make(a.date, a.episode, a.force, not a.no_upload, a.dry_run), ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
