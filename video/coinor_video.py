# ----------------------------------------------------------------------------- choosing the chapter
def lagos_date(iso):
    t = dt.datetime.fromisoformat(iso)
    return (t + dt.timedelta(hours=CFG["tz_hours"])).date().isoformat()


def pick_episode(feed, date=None, number=None):
    eps = [e for e in feed.get("episodes", []) if e.get("status") == "approved" and e.get("published_at")]
    if number is not None:
        return next((e for e in eps if e["number"] == number), None)
    todays = [e for e in eps if lagos_date(e["published_at"]) == date]
    return max(todays, key=lambda e: e["number"]) if todays else None


# ----------------------------------------------------------------------------- the narration (no AI)
def clean(text):
    t = text.replace("*", "").replace("—", ", ").replace("–", ", ").replace("…", "...")
    t = re.sub(r"\s+", " ", t)
    return t.strip()


def sentences(text):
    return [s.strip() for s in re.split(r"(?<=[.!?])\s+(?=[A-Z\"'])", clean(text)) if s.strip()]


def narration(body, max_words):
    out, n = [], 0
    for para in re.split(r"\n\s*\n", body):
        for s in sentences(para):
            w = len(s.split())
            if n + w > max_words and out:
                return out
            out.append(s); n += w
    return out


