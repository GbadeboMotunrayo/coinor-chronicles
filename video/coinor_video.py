def find_image(obj):
    """Return the bytes of the last base64 image anywhere in a Gemini reply, whatever the reply's shape."""
    import base64
    hits = []
    def walk(o):
        if isinstance(o, dict):
            d = o.get("data") or (o.get("inlineData") or o.get("inline_data") or {}).get("data")
            mt = str(o.get("mime_type") or o.get("mimeType") or (o.get("inlineData") or o.get("inline_data") or {}).get("mimeType") or "")
            if isinstance(d, str) and len(d) > 2000 and (o.get("type") == "image" or mt.startswith("image/") or "inlineData" in o or "inline_data" in o):
                hits.append(d)
            for v in o.values():
                walk(v)
        elif isinstance(o, list):
            for v in o:
                walk(v)
    walk(obj)
    return base64.b64decode(hits[-1]) if hits else None


def gemini_image(prompt, refs, dest, key, urlopen=urllib.request.urlopen):
    """One picture from Gemini, with up to 2 reference pictures so the same face and clothes come back.
    Tries the documented Interactions API, then the older generateContent. Returns True on success; False on any refusal."""
    import base64
    ref_b64 = [base64.b64encode(open(r, "rb").read()).decode() for r in refs if os.path.exists(r)]
    for model in CFG["gemini_image_models"]:
        attempts = [
            ("https://generativelanguage.googleapis.com/v1beta/interactions",
             {"model": model, "input": [{"type": "text", "text": prompt}] + [{"type": "image", "mime_type": "image/png", "data": b} for b in ref_b64],
              "response_format": {"type": "image", "mime_type": "image/png", "aspect_ratio": "9:16"}}),
            (f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent",
             {"contents": [{"parts": [{"text": prompt}] + [{"inlineData": {"mimeType": "image/png", "data": b}} for b in ref_b64]}],
              "generationConfig": {"responseModalities": ["IMAGE"], "imageConfig": {"aspectRatio": "9:16"}}}),
        ]
        for url, body in attempts:
            try:
                req = urllib.request.Request(url, json.dumps(body).encode(), {"Content-Type": "application/json", "x-goog-api-key": key})
                img = find_image(json.loads(urlopen(req, timeout=120).read()))
                if img and len(img) > 5000:
                    open(dest, "wb").write(img)
                    return True
            except urllib.error.HTTPError as e:
                log("gemini_image_http", model=model, code=e.code)
                if e.code == 429:
                    return False            # out of quota: stop spending requests this run
            except Exception as e:
                log("gemini_image_error", model=model, why=type(e).__name__)
    return False


def character_ref(name, cast, style, key):
    """The reference sheet for one character, made once and kept, so every later picture can copy it."""
    os.makedirs(CFG["character_dir"], exist_ok=True)
    p = os.path.join(CFG["character_dir"], re.sub(r"\W+", "_", name.lower()) + ".png")
    if os.path.exists(p):
        return p
    prompt = (f"Character reference sheet. Full-body front view of {name}: {cast[name]}. Plain neutral parchment-grey background, "
              f"centred, the whole figure visible, one figure only. Style: {style}.")
    return p if gemini_image(prompt, [], p, key) else None


def scene_prompt_gemini(scene, names, cast, style):
    who = "; ".join(f"{n} is {cast[n]}" for n in names)
    t = re.sub(r"\b(?:Heaven|Gate)\s*\d+\b", "the great gate", scene)
    keep = "Keep each character exactly as in the reference pictures: same face, hair, clothes and colours. " if names else ""
    return f"{keep}Draw this scene as a vertical 9:16 picture: {t}. {('Characters: ' + who + '. ') if who else ''}Style: {style}."


# ----------------------------------------------------------------------------- pictures
def fetch_image(prompt, seed, dest):
    url = ("https://image.pollinations.ai/prompt/" + urllib.parse.quote(prompt) +
           f"?width={CFG['w']}&height={CFG['h']}&nologo=true&model=flux&seed={seed}")
    for attempt in range(CFG["image_tries"]):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": "CoinorChronicles/1.0"})
            with urllib.request.urlopen(req, timeout=75) as r:
                data = r.read()
            if len(data) > 8000 and data[:3] == b"\xff\xd8\xff":
                open(dest, "wb").write(data)
                return True
        except urllib.error.HTTPError as e:
            log("image_retry", attempt=attempt + 1, why=f"http {e.code}")
        except Exception as e:
            log("image_retry", attempt=attempt + 1, why=type(e).__name__)
        time.sleep(12 * (attempt + 1))
    return False


def esc(t):                 # ffmpeg drawtext escaping
    return t.replace("\\", "\\\\").replace(":", "\\:").replace("'", "’").replace("%", "\\%").replace(",", "\\,")


def fallback_card(text, dest):
    w, h = CFG["w"], CFG["h"]
    words = text.split(); lines, cur = [], ""
    for wd in words[:22]:
        if len(cur) + len(wd) > 24:
            lines.append(cur); cur = wd
        else:
            cur = (cur + " " + wd).strip()
    lines.append(cur)
    dt_ = ",".join(f"drawtext=fontfile={CFG['font_serif']}:text='{esc(l)}':fontcolor=0x2a1b0d:fontsize=58:x=(w-text_w)/2:y={760 + i * 84}" for i, l in enumerate(lines[:8]))
    run(["ffmpeg", "-y", "-v", "error", "-f", "lavfi", "-i", f"color=c=0xe7d3a2:s={w}x{h}", "-vf",
         f"vignette=PI/3,{dt_}", "-frames:v", "1", dest])


def run(cmd, **kw):
    r = subprocess.run(cmd, capture_output=True, text=True, **kw)
    if r.returncode:
        raise RuntimeError(f"{os.path.basename(cmd[0])} failed: {r.stderr.strip()[-400:]}")
    return r


# ----------------------------------------------------------------------------- voice and captions
def speak(sentence, wav):
    p = subprocess.run([CFG["piper_python"], "-m", "piper", "-m", CFG["voice"], "-f", wav], input=sentence, capture_output=True, text=True, timeout=180)
    if p.returncode or not os.path.exists(wav):
        raise RuntimeError("piper failed: " + p.stderr.strip()[-300:])


def duration(path):
    r = run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "default=nw=1:nk=1", path])
    return float(r.stdout.strip())


def ass_time(t):
    cs = int(round(t * 100)); h, rem = divmod(cs, 360000); m, rem = divmod(rem, 6000); s, c = divmod(rem, 100)
    return f"{h}:{m:02d}:{s:02d}.{c:02d}"


def make_ass(timed, path):
    """timed: [(sentence, start, end)]. Captions are chunks of up to 5 words spread over each sentence by length."""
    head = ("[Script Info]\nScriptType: v4.00+\nPlayResX: %d\nPlayResY: %d\n\n[V4+ Styles]\n"
            "Format: Name,Fontname,Fontsize,PrimaryColour,SecondaryColour,OutlineColour,BackColour,Bold,Italic,Underline,StrikeOut,ScaleX,ScaleY,Spacing,Angle,BorderStyle,Outline,Shadow,Alignment,MarginL,MarginR,MarginV,Encoding\n"
            "Style: Cap,DejaVu Serif,66,&H00FFFFFF,&H00FFFFFF,&H00101010,&H80000000,-1,0,0,0,100,100,0,0,1,5,2,2,70,70,330,1\n\n"
            "[Events]\nFormat: Layer,Start,End,Style,Name,MarginL,MarginR,MarginV,Effect,Text\n") % (CFG["w"], CFG["h"])
    ev = []
    for text, a, b in timed:
        ws = text.split(); chunks = [ws[i:i + 5] for i in range(0, len(ws), 5)] or [[]]
        total = sum(len(" ".join(c)) for c in chunks) or 1; t = a
        for c in chunks:
            d = (b - a) * len(" ".join(c)) / total
            ev.append(f"Dialogue: 0,{ass_time(t)},{ass_time(t + d)},Cap,,0,0,0,,{' '.join(c).replace('{', '(').replace('}', ')')}")
            t += d
    open(path, "w", encoding="utf-8").write(head + "\n".join(ev) + "\n")


# ----------------------------------------------------------------------------- the render
def build(ep, work, out_mp4):
    w, h, fps = CFG["w"], CFG["h"], CFG["fps"]
    sents = narration(ep["body"], CFG["max_words"]) + [OUTRO]
    # 1. voice, one sentence at a time, so the captions know exactly when each is spoken
    parts, timed, t = [], [], 0.4
    gap = f"{work}/gap.wav"
    run(["ffmpeg", "-y", "-v", "error", "-f", "lavfi", "-i", f"anullsrc=r=22050:cl=mono", "-t", str(CFG["pause"]), gap])
    lead = f"{work}/lead.wav"
    run(["ffmpeg", "-y", "-v", "error", "-f", "lavfi", "-i", "anullsrc=r=22050:cl=mono", "-t", "0.4", lead])
    parts.append(lead)
    for i, s in enumerate(sents):
        wav = f"{work}/s{i:02d}.wav"; speak(s, wav); d = duration(wav) / CFG["voice_pitch"]
        timed.append((s, t, t + d)); t += d + CFG["pause"]; parts += [wav, gap]
    lst = f"{work}/list.txt"; open(lst, "w").write("".join(f"file '{p}'\n" for p in parts))
    voice_raw = f"{work}/voice_raw.wav"
    run(["ffmpeg", "-y", "-v", "error", "-f", "concat", "-safe", "0", "-i", lst, "-c", "copy", voice_raw])
    total = t + 0.8
    # 2. pictures
    sc = scenes(ep); imgs = []
    style, cast = load_cast(); gkey = env_value("GEMINI_API_KEY"); gem_ok = bool(gkey); gem_fail = 0
    for i, scene in enumerate(sc):
        p = f"{work}/img{i}.jpg"
        if gem_ok:
            names = cast_in(scene, cast)
            refs = [r for r in (character_ref(n, cast, style, gkey) for n in names) if r]
            if gemini_image(scene_prompt_gemini(scene, names, cast, style), refs, p, gkey):
                imgs.append(p); log("scene_gemini", scene=i, characters=names); continue
            gem_fail += 1
            if gem_fail >= 2:
                gem_ok = False          # two misses in a row (quota or outage): stop spending requests this run
        if i:
            time.sleep(CFG["image_gap"])
        if not fetch_image(image_prompt(scene), ep["number"] * 10 + i, p):
            log("image_fallback", scene=i)
            good = [q for q in imgs if os.path.exists(q) and not q.endswith("card.jpg")]
            if good:
                run(["ffmpeg", "-y", "-v", "error", "-i", good[i % len(good)], "-vf", "hflip", "-frames:v", "1", p])   # same look, mirrored
            else:
                fallback_card(ep["title"], p)
        imgs.append(p)
    # 3. captions
    ass = f"{work}/cap.ass"; make_ass(timed[:-1] + [timed[-1]], ass)
    # 4. picture track: slow zoom on each still, in and out alternately
    per = total / len(imgs); frames = int(per * fps) + 1
    clips = []
    for i, p in enumerate(imgs):
        z = ("min(zoom+0.00055,1.16)" if i % 2 == 0 else "if(eq(on,0),1.16,max(zoom-0.00055,1.0))")
        c = f"{work}/clip{i}.mp4"
        run(["ffmpeg", "-y", "-v", "error", "-loop", "1", "-i", p, "-vf",
             f"crop=iw:ih*0.93:0:0,scale={int(w * 1.25)}:{int(h * 1.25)}:force_original_aspect_ratio=increase,crop={int(w * 1.25)}:{int(h * 1.25)},"
             f"zoompan=z='{z}':x='iw/2-(iw/zoom/2)':y='ih/2-(ih/zoom/2)':d={frames}:s={w}x{h}:fps={fps},format=yuv420p",
             "-frames:v", str(frames), "-c:v", "libx264", "-preset", "veryfast", "-crf", "20", c])
        clips.append(c)
    clist = f"{work}/clips.txt"; open(clist, "w").write("".join(f"file '{c}'\n" for c in clips))
    pics = f"{work}/pics.mp4"
    run(["ffmpeg", "-y", "-v", "error", "-f", "concat", "-safe", "0", "-i", clist, "-c", "copy", pics])
    # 5. sound: the voice, a little lower, over a quiet drone made by ffmpeg
    voice = f"{work}/voice.wav"
    run(["ffmpeg", "-y", "-v", "error", "-i", voice_raw, "-af",
         f"asetrate=22050*{CFG['voice_pitch']},aresample=44100,atempo={1 / CFG['voice_pitch']:.4f},"
         "highpass=f=70,acompressor=threshold=-18dB:ratio=3,volume=1.4", voice])
    drone = f"{work}/drone.wav"
    run(["ffmpeg", "-y", "-v", "error", "-f", "lavfi", "-i", f"sine=f=55:d={total}", "-f", "lavfi", "-i", f"sine=f=82.4:d={total}",
         "-f", "lavfi", "-i", f"sine=f=110:d={total}", "-f", "lavfi", "-i", f"anoisesrc=d={total}:c=pink:a=0.02", "-filter_complex",
         "[0][1][2][3]amix=inputs=4:normalize=0,lowpass=f=420,aecho=0.8:0.7:90:0.35,volume=0.22,"
         f"afade=t=in:d=2,afade=t=out:st={max(total - 3, 0)}:d=3[a]", "-map", "[a]", "-ar", "44100", drone])
    mix = f"{work}/mix.wav"
    run(["ffmpeg", "-y", "-v", "error", "-i", voice, "-i", drone, "-filter_complex",
         "[0]apad[v];[v][1]amix=inputs=2:duration=shortest:normalize=0,loudnorm=I=-16:TP=-1.5:LRA=11[a]", "-map", "[a]", "-t", f"{total:.2f}", "-ar", "44100", mix])
    # 6. final: pictures + captions + labels + sound
    label = esc(f"CoinorChronicles  ·  Episode {ep['number']}")
    foot = esc("coinorchonicles.space")
    note = esc("Fiction · AI-made pictures · Not financial advice")
    vf = (f"subtitles={ass}:fontsdir=/usr/share/fonts/truetype/dejavu,"
          f"drawtext=fontfile={CFG['font_sans']}:text='{label}':fontcolor=white@0.92:fontsize=40:x=(w-text_w)/2:y=96:box=1:boxcolor=black@0.35:boxborderw=18,"
          f"drawtext=fontfile={CFG['font_serif']}:text='{foot}':fontcolor=0xf0d9a0:fontsize=44:x=(w-text_w)/2:y=h-170,"
          f"drawtext=fontfile={CFG['font_sans']}:text='{note}':fontcolor=white@0.8:fontsize=30:x=(w-text_w)/2:y=h-110")
    run(["ffmpeg", "-y", "-v", "error", "-i", pics, "-i", mix, "-vf", vf, "-map", "0:v", "-map", "1:a", "-c:v", "libx264", "-preset", "veryfast",
         "-crf", "23", "-pix_fmt", "yuv420p", "-c:a", "aac", "-b:a", "160k", "-shortest", "-movflags", "+faststart", out_mp4])
    return {"seconds": round(duration(out_mp4), 1), "words": sum(len(s.split()) for s in sents), "images_ai": sum(1 for _ in imgs), "sentences": sents}


